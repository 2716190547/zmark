pub fn localize_palette_name<'a>(id: &'a str, strings: &'a I18nStrings) -> &'a str {
    match id {
        "default" | "miaoyan" => strings.palette_default,
        "claude" => strings.palette_claude,
        "macos" => strings.palette_macos,
        "tokyo-night" => strings.palette_tokyo_night,
        "nord" => strings.palette_nord,
        "github" => strings.palette_github,
        "solarized" => strings.palette_solarized,
        "one-dark" => strings.palette_one_dark,
        _ => id,
    }
}

pub fn get_strings(locale: SupportedLocale) -> &'static I18nStrings {
    match locale.resolve() {
        SupportedLocale::ZhCn => &ZH_CN,
        SupportedLocale::ZhTw => &ZH_TW,
        SupportedLocale::En | SupportedLocale::Auto => &EN,
        SupportedLocale::Ja => &JA,
        SupportedLocale::Ko => &KO,
        SupportedLocale::Fr => &FR,
        SupportedLocale::De => &DE,
        SupportedLocale::Es => &ES,
        SupportedLocale::Ru => &RU,
        SupportedLocale::Pt => &PT,
    }
}

